#!/bin/bash
# One-command setup for the LinkedIn GTM commenting routine (macOS / Linux).
#
#   curl -fsSL https://raw.githubusercontent.com/rohitabrahamgeorge/rohitabrahamgeorge/claude/linkedin-engagement-automation-h7dz64/linkedin-commenter/install.sh | bash
#
# What it does (safe to re-run):
#   1. clones/updates the repo into ~/linkedin-commenter-repo
#   2. installs Python Playwright + Chromium
#   3. installs Claude Code CLI if missing and checks it is signed in
#   4. opens a browser window so you log in to LinkedIn once (password stays on your machine)
#   5. schedules the routine Mon/Wed/Fri 10:30 local time (launchd on macOS, cron on Linux)
set -euo pipefail

REPO_URL="https://github.com/rohitabrahamgeorge/rohitabrahamgeorge.git"
BRANCH="${LI_BRANCH:-claude/linkedin-engagement-automation-h7dz64}"
DIR="${LI_DIR:-$HOME/linkedin-commenter-repo}"
LABEL="com.linkedin-gtm-commenter"
say() { printf "\n\033[1m==> %s\033[0m\n" "$*"; }

say "1/5 Getting the routine files into $DIR"
command -v git >/dev/null || { echo "git is required (macOS: run 'xcode-select --install')"; exit 1; }
if [ -d "$DIR/.git" ]; then
  git -C "$DIR" fetch -q origin "$BRANCH" && git -C "$DIR" checkout -q "$BRANCH" && git -C "$DIR" pull -q --ff-only origin "$BRANCH" || true
else
  git clone -q -b "$BRANCH" "$REPO_URL" "$DIR"
fi
cd "$DIR"

say "2/5 Installing Playwright"
PY="$(command -v python3 || true)"
[ -n "$PY" ] || { echo "python3 is required: install from https://www.python.org/downloads/"; exit 1; }
"$PY" -m pip install -q --user --upgrade playwright 2>/dev/null || "$PY" -m pip install -q --upgrade playwright \
  || "$PY" -m pip install -q --break-system-packages --upgrade playwright
"$PY" -m playwright install chromium

say "3/5 Checking Claude Code"
export PATH="$HOME/.local/bin:$HOME/.claude/local:/opt/homebrew/bin:/usr/local/bin:$PATH"
if ! command -v claude >/dev/null; then
  curl -fsSL https://claude.ai/install.sh | bash
  export PATH="$HOME/.local/bin:$PATH"
fi
CLAUDE="$(command -v claude)"
if ! "$CLAUDE" -p "Reply with the word ok" </dev/null >/dev/null 2>&1; then
  echo "Claude Code needs you to sign in once. Running 'claude' now: sign in, then type /exit."
  "$CLAUDE" </dev/tty || true
fi

say "4/5 LinkedIn login (a browser window will open; log in and finish any 2FA)"
if "$PY" linkedin-commenter/scripts/li.py check 2>/dev/null | grep -q '"logged_in": true'; then
  echo "Already logged in."
else
  "$PY" linkedin-commenter/scripts/li.py login
  "$PY" linkedin-commenter/scripts/li.py check | grep -q '"logged_in": true' \
    || { echo "LinkedIn login not detected. Re-run this installer to try again."; exit 1; }
fi

say "5/5 Scheduling Mon/Wed/Fri 10:30 (your computer's local time)"
RUNNER="$DIR/linkedin-commenter/run.sh"
cat > "$RUNNER" <<EOF
#!/bin/bash
# Generated by install.sh: runs one commenting session headless via Claude Code.
export PATH="$(dirname "$CLAUDE"):$(dirname "$PY"):\$PATH"
cd "$DIR" || exit 1
git pull -q --ff-only origin "$BRANCH" 2>/dev/null || true
mkdir -p linkedin-commenter/state
echo "=== \$(date) ===" >> linkedin-commenter/state/run.log
"$CLAUDE" -p "/linkedin-gtm-commenter Run today's routine: 25 comments, then show me the report." \\
  --permission-mode dontAsk \\
  --allowedTools "Skill" "Read" "Write" "Edit" "Glob" "Grep" \\
    "Bash(python3:*)" "Bash($PY:*)" "Bash(git:*)" "Bash(sleep:*)" "Bash(date:*)" "Bash(mkdir:*)" \\
  >> linkedin-commenter/state/run.log 2>&1
EOF
chmod +x "$RUNNER"

if [ "$(uname)" = "Darwin" ]; then
  PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
  mkdir -p "$HOME/Library/LaunchAgents"
  cal=""
  for d in 1 3 5; do cal+="<dict><key>Weekday</key><integer>$d</integer><key>Hour</key><integer>10</integer><key>Minute</key><integer>30</integer></dict>"; done
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key><array><string>/bin/bash</string><string>$RUNNER</string></array>
  <key>StartCalendarInterval</key><array>$cal</array>
  <key>StandardOutPath</key><string>$DIR/linkedin-commenter/state/launchd.log</string>
  <key>StandardErrorPath</key><string>$DIR/linkedin-commenter/state/launchd.log</string>
</dict></plist>
EOF
  launchctl unload "$PLIST" 2>/dev/null || true
  launchctl load "$PLIST"
  # wake the Mac a few minutes before each run (asks for your Mac password; skip with Ctrl+C)
  echo "Optional: wake the Mac at 10:25 Mon/Wed/Fri so runs aren't missed (needs your Mac password)."
  sudo pmset repeat wakeorpoweron MWF 10:25:00 </dev/tty || echo "Skipped auto-wake."
  echo "Scheduled with launchd ($PLIST). If the Mac is asleep at 10:30, the run happens when it wakes."
else
  line="30 10 * * 1,3,5 /bin/bash $RUNNER"
  ( crontab -l 2>/dev/null | grep -v "linkedin-commenter/run.sh"; echo "$line" ) | crontab -
  echo "Scheduled with cron: $line"
fi

cat <<EOF

All set. The routine now runs on its own every Mon/Wed/Fri at 10:30.
  Reports:  $DIR/linkedin-commenter/reports/
  Run log:  $DIR/linkedin-commenter/state/run.log
  Run now (test):  bash $RUNNER
  Dry run (no posting):  cd $DIR && claude "/linkedin-gtm-commenter dry run, 5 creators"
  Uninstall: macOS 'launchctl unload $HOME/Library/LaunchAgents/$LABEL.plist'; Linux 'crontab -e'
EOF
